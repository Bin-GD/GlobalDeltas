function [ClassTable,....
                ClassSubTable]=AnalysisClass_PopArea(OpenPath)

    load(OpenPath);
    
    ClassVM             =   table2array( Popu_AreaT(:,7:8) );
    
    Valid_log           =   ClassVM(:,1)~=0;
    
    Class1_log          =   ClassVM(:,1)==1;
    Class2_log          =   ClassVM(:,1)==2;
    Class3_log          =   ClassVM(:,1)==3;
    
    Enhance_log         =   ClassVM(:,2)==1;
    
    Valid_Num               =   length(Valid_log(Valid_log));
    
    Class1_2_Num            =   length(Valid_log(Class1_log | Class2_log));
    Class1_Num              =   length(Class1_log(Class1_log));
    Class2_Num              =   length(Class2_log(Class2_log));
    Class3_Num              =   length(Class3_log(Class3_log));
    
    
    Class1_2_Enhance_Num    =   length(Valid_log( (Class1_log | Class2_log) & Enhance_log));
    Class1_2_Other_Num      =   length(Valid_log( (Class1_log | Class2_log) & ~Enhance_log));
    
    
    Class1_Enhance_Num      =   length(Class1_log(Class1_log & Enhance_log));
    Class1_Other_Num        =   length(Class1_log(Class1_log & ~Enhance_log));
    
    Class2_Enhance_Num      =   length(Class2_log(Class2_log & Enhance_log));
    Class2_Other_Num        =   length(Class2_log(Class2_log & ~Enhance_log));
    
    Class3_Enhance_Num      =   length(Class3_log(Class3_log & Enhance_log));
    Class3_Other_Num        =   length(Class3_log(Class3_log & ~Enhance_log));
    
    
    ClassTable              =   table(Valid_Num,.....
                                    Class1_2_Num,....
                                    Class1_2_Num/Valid_Num*100,....    
                                    Class1_Num,....
                                    Class1_Num/Valid_Num*100,....
                                    Class2_Num,....
                                    Class2_Num/Valid_Num*100,....
                                    Class3_Num,....
                                    Class3_Num/Valid_Num*100,....
                                    'VariableNames',...
                                    {'Analysis Num',...
                                    'C1_2 Num',...
                                    'C1_2 Per',...
                                    'C1 Num',...
                                    'C1 Per',...
                                    'C2 Num',...
                                    'C2 Per',...
                                    'C3 Num',...
                                    'C3 Per'});
    
    ClassSubTable              =   table(Valid_Num,.....
                                    Class1_2_Enhance_Num,....
                                    Class1_2_Enhance_Num/Valid_Num*100,....    
                                    Class1_2_Other_Num,....
                                    Class1_2_Other_Num/Valid_Num*100,....
                                    ......
                                    Class1_Enhance_Num,....
                                    Class1_Enhance_Num/Valid_Num*100,....
                                    Class1_Other_Num,....
                                    Class1_Other_Num/Valid_Num*100,....
                                    .......
                                    Class2_Enhance_Num,....
                                    Class2_Enhance_Num/Valid_Num*100,....
                                    Class2_Other_Num,....
                                    Class2_Other_Num/Valid_Num*100,....  
                                    .......
                                    Class3_Enhance_Num,....
                                    Class3_Enhance_Num/Valid_Num*100,....
                                    Class3_Other_Num,....
                                    Class3_Other_Num/Valid_Num*100,....
                                    'VariableNames',...
                                    {'Analysis Num',...
                                    'C1_2 Enhance Num',...
                                    'C1_2 Enhance Per',...
                                    'C1_2 Other Num',...
                                    'C1_2 Other Per',...
                                    .....
                                    'C1 Enhance Num',...
                                    'C1 Enhance Per',...
                                    'C1 Other Num',...
                                    'C1 Other Per',...
                                    ....
                                    'C2 Enhance Num',...
                                    'C2 Enhance Per',...
                                    'C2 Other Num',...
                                    'C2 Other Per',...
                                    ......
                                    'C3 Enhance Num',...
                                    'C3 Enhance Per',...
                                    'C3 Other Num',...
                                    'C3 Other Per'.....
                                    });

    


end