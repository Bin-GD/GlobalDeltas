function [ClassTable,....
             MS_ClassTable]     =   GetClassTable(ClassDataV,...
                                                        Class_UN)

    L                       =   length(ClassDataV);
    Class_1_log             =   ClassDataV==0;
    Class_2_log             =   ClassDataV==1;
    Class_3_log             =   ClassDataV==2;
    Class_4_log             =   ClassDataV==3;
    
    Class_1_Num             =   length(Class_1_log(Class_1_log));
    Class_2_Num             =   length(Class_2_log(Class_2_log));
    Class_3_Num             =   length(Class_3_log(Class_3_log));
    Class_4_Num             =   length(Class_4_log(Class_4_log));
    
    ClassTable              =   table(Class_1_Num,...
                                        Class_1_Num/L*100,...
                                        Class_2_Num,...
                                        Class_2_Num/L*100,...
                                        Class_3_Num,...
                                        Class_3_Num/L*100,...
                                        Class_4_Num,...
                                        Class_4_Num/L*100,....
                                        'VariableNames',...
                                        {'C1 Num',...
                                        'C1 Per(%)',...
                                        'C2 Num',...
                                        'C2 Per(%)',...
                                        'C3 Num',...
                                        'C3 Per(%)',...
                                        'C4 Num',...
                                        'C4 Per(%)'});


    UnvariableClass_log             =   Class_UN==1;
    Variable2Class_log              =   Class_UN==2;
    Variable3Class_log              =   Class_UN==3;
    Variable4Class_log              =   Class_UN==4;


    UClass_1_log                    =   UnvariableClass_log&Class_1_log;
    UClass_2_log                    =   UnvariableClass_log&Class_2_log;
    UClass_3_log                    =   UnvariableClass_log&Class_3_log;
    UClass_4_log                    =   UnvariableClass_log&Class_4_log;

    UClass_1_Num                    =   length(UClass_1_log(UClass_1_log));
    UClass_2_Num                    =   length(UClass_2_log(UClass_2_log));
    UClass_3_Num                    =   length(UClass_3_log(UClass_3_log));
    UClass_4_Num                    =   length(UClass_4_log(UClass_4_log));   


    V2Class_Num                     =   length(Variable2Class_log(Variable2Class_log));
    V3Class_Num                     =   length(Variable3Class_log(Variable3Class_log));
    V4Class_Num                     =   length(Variable4Class_log(Variable4Class_log));


    MS_ClassTable                   =   table(UClass_1_Num,...
                                        UClass_1_Num/L*100,...
                                        UClass_2_Num,...
                                        UClass_2_Num/L*100,...
                                        UClass_3_Num,...
                                        UClass_3_Num/L*100,...
                                        UClass_4_Num,...
                                        UClass_4_Num/L*100,....
                                        V2Class_Num,...
                                        V2Class_Num/L*100,....
                                        V3Class_Num,...
                                        V3Class_Num/L*100,....
                                        V4Class_Num,...
                                        V4Class_Num/L*100,....
                                        'VariableNames',...
                                        {'Unvariable C1 Num',...
                                        'Unvariable C1 Per(%)',...
                                        'Unvariable C2 Num',...
                                        'Unvariable C2 Per(%)',...
                                        'Unvariable C3 Num',...
                                        'Unvariable C3 Per(%)',...
                                        'Unvariable C4 Num',...
                                        'Unvariable C4 Per(%)',....
                                        'Variable 2C Num',...
                                        'Variable 2C Per(%)',...
                                        'Variable 3C Num',...
                                        'Variable 3C Per(%)',...
                                        'Variable 4C Num',...
                                        'Variable 4C Per(%)'});
end