function [PopSlopeTable,...
                SlopeM1_R2Table]        =   GetSlopeR2AnalysisResults(PopSlopeR2...
                                                                )
    % Population slope & R2 info analysis results 
    %% ====================================================================
    Less0_log               =   PopSlopeR2(:,1)<=0;
    More0_log               =   PopSlopeR2(:,1)>0;
    More05_log              =   PopSlopeR2(:,1)>0.5;
    More1_log               =   PopSlopeR2(:,1)>1;
    LN                      =   length(PopSlopeR2(:,1));
    
    PopSlopeTable           =   table(length(Less0_log(Less0_log)),...
                                        length(Less0_log(Less0_log))/LN*100,...
                                        .....
                                        length(More0_log(More0_log)),...
                                        length(More0_log(More0_log))/LN*100,...
                                        .....
                                        length(More05_log(More05_log)),...
                                        length(More05_log(More05_log))/LN*100,...
                                        .....
                                        length(More1_log(More1_log)),...
                                        length(More1_log(More1_log))/LN*100,...
                                        'VariableNames',....
                                        {'<=0',...
                                        '<=0 Per',...
                                        '>0',...
                                        '>0 Per',...
                                        '>0.5',....
                                        '>0.5 Per',...
                                        '>1',...
                                        '>1 Per'});

    %% ====================================================================

    
    fPopSlopeR2     =   PopSlopeR2(More1_log,2);
    
    R2_More06_log   =   fPopSlopeR2>0.6;
    R2_More08_log   =   fPopSlopeR2>0.8;
    
    SlopeM1_R2Table         =   table(length(R2_More06_log(R2_More06_log))/length(R2_More06_log)*100,...
                                    length(R2_More08_log(R2_More08_log))/length(R2_More08_log)*100,...
                                    'VariableNames',{'R2>0.6','R2>0.8'});

end